-- AppHub v1. Apply in Supabase SQL Editor before deploying the frontend.
create extension if not exists pgcrypto;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 100),
  url text not null check (url ~ '^https://[^[:space:]]+$' and length(url) <= 2048),
  description text not null default '' check (length(description)<=500),
  category text not null default 'General' check (length(category)<=60),
  icon text not null default '🌐' check (length(icon)<=20),
  visibility text not null default 'published' check (visibility in ('published','unlisted')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.access_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_email text not null,
  event_type text not null check (event_type in ('login','visit','launch','logout')),
  application_id uuid references public.applications(id) on delete set null,
  application_name text,
  target_url text,
  browser text,
  os text,
  device_type text,
  city text,
  region text,
  country text,
  session_id text,
  created_at timestamptz not null default now()
);
create index if not exists access_events_user_time_idx on public.access_events(user_id,created_at desc);
create index if not exists access_events_time_idx on public.access_events(created_at desc);
create index if not exists access_events_event_time_idx on public.access_events(event_type,created_at desc);

alter table public.admin_users enable row level security;
alter table public.applications enable row level security;
alter table public.access_events enable row level security;

-- Admin membership is tied to auth.uid(), not user-editable Google metadata.
create policy "read own admin membership" on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()));
-- No client insert/update/delete policies for admin_users. Bootstrap via SQL Editor.

create policy "read published apps or admin apps" on public.applications for select to authenticated
  using (visibility='published' or exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
create policy "admin inserts applications" on public.applications for insert to authenticated
  with check(exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())) and created_by=(select auth.uid()));
create policy "admin updates applications" on public.applications for update to authenticated
  using(exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())))
  with check(exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
create policy "admin deletes applications" on public.applications for delete to authenticated
  using(exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
create policy "admin reads access events" on public.access_events for select to authenticated
  using(exists(select 1 from public.admin_users a where a.user_id=(select auth.uid())));
-- No client-side insert/update/delete policies for events. Edge Function inserts with a server-only key.

revoke all on public.admin_users,public.applications,public.access_events from anon;
grant select on public.admin_users to authenticated;
grant select,insert,update,delete on public.applications to authenticated;
grant select on public.access_events to authenticated;

